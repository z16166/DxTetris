#!/usr/bin/env python3
"""embed_csos.py — embed fxc .cso blobs as C arrays in header (MINE, final; deterministic).
Usage: py -3 embed_csos.py <vs.cso> <ps.cso> <out.h>
"""
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gencommon import write_section


def arr(name, data):
    lines = [f"static const unsigned char {name}[] = {{"]
    lines.append(", ".join(f"0x{b:02x}" for b in data))
    lines.append("};")
    return f"{name}_len", lines


def main():
    vs_path, ps_path = sys.argv[1], sys.argv[2]
    out_dir = sys.argv[3] if len(sys.argv) > 3 else None
    vs = open(vs_path, "rb").read()
    ps = open(ps_path, "rb").read()
    lines = ["// cso arrays (generated by tools/embed_csos.py) — fxc-compiled blobs"]
    for name, data in [("game_vs_cso", vs), ("game_ps_cso", ps)]:
        lenname, body = arr(name, data)
        lines.append(f"static const unsigned int {lenname} = {len(data)}u;")
        lines.extend(body)
    write_section("cso", lines)
    print("wrote section_cso.inc")

if __name__ == "__main__":
    main()
