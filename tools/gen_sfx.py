#!/usr/bin/env python3
"""gen_sfx.py — sound effect generator (synth -> WAV headers; pure Python). — MINE, final.
Deterministic (seeded noise), events: key_move, key_rotate, key_hold, key_holdfail,
softstep, harddrop, lock, clear1-4, combo, gameover, levelup, pause/unpause, start/select.
Run standalone: py -3 tools/gen_sfx.py  (mechanical run)
"""
import os, sys, math, wave, struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
from gencommon import write_header   # shared emitter (mine, stable)

RATE = 44100
SEED = 1234   # deterministic RNG seed (no time dependency)

def rng(seed):
    s = seed & 0xFFFFFFFFFFFFFF
    def r():
        nonlocal s
        s ^= (s << 7) & 0xFFFFFFFFFFFFFF; s &= 0xFFFFFFFFFFFFFFFF
        s ^= s >> 9
        return s / 0xFFFFFFFFFFFFFFFF
    return r

def env(t, a, d):   # attack/decay in seconds -> 0..1
    if t < a: return t / max(a, 1e-6)
    return max(0.0, 1.0 - (t - a) / max(d, 1e-6))

def tone(f0, dur, vol=0.5, a=0.005, d=0.12, shape="sine", f1=None, vib=0.0, seed=SEED, noise=0.0):
    r = rng(seed)
    n = int(dur * RATE)
    smp = []
    ph = 0.0
    for i in range(n):
        t = i / RATE
        f = f0 + (f1 - f0) * (i / n) if f1 else f0
        if shape == "sine":
            v = math.sin(2*math.pi*ph)
        elif shape == "square":
            v = 1.0 if (ph % 1.0) < 0.5 else -1.0
        elif shape == "saw":
            v = 2*((ph % 1.0)) - 1
        else:
            v = 2*math.pi*ph  # noise-ish fallback
        if vib:
            v += vib * math.sin(2*math.pi*(t*7.3))
        v *= vol * env(t, a, d)
        v += noise * (r() - 0.5) * 2 * vol * env(t, a, d)
        ph += f / RATE
        smp.append(max(-1.0, min(1.0, v)))
    return smp

def write_wav(name, samples, vol=0.9):
    p = os.path.join(ROOT, "assets", "src")
    os.makedirs(p, exist_ok=True)
    p = os.path.join(p, name + ".wav")
    w = wave.open(p, "w")
    w.setnchannels(1); w.setsampwidth(2); w.setframerate(RATE)
    w.writeframes(b"".join(struct.pack("h", int(max(-1.0, min(1.0, s*vol))*32767)) for s in samples))
    w.close()
    return p

def main():
    # build event sample pools (determin)
    events = {}
    events["key_move"]   = tone(900, 0.05, 0.35, 0.002, 0.05, shape="square", noise=0.15, seed=SEED)
    events["key_rotate"] = tone(1300, 0.06, 0.35, 0.002, 0.06, shape="square", noise=0.10, seed=SEED+1)
    events["key_hold"]   = tone(600, 0.09, 0.5, 0.003, 0.09)
    events["key_holdfail"] = tone(420, 0.10, 0.30, 0.003, 0.10, vib=8, seed=SEED+2)
    events["softstep"]   = tone(1600, 0.03, 0.15, 0.001, 0.03, shape="square", noise=0.3, seed=SEED+3)
    events["harddrop"]   = tone(180, 0.12, 0.6, 0.001, 0.12, noise=0.6, seed=SEED+4)
    events["lock"]       = tone(750, 0.07, 0.35, 0.001, 0.07, noise=0.25, seed=SEED+5)
    for n, f in [(1, 900), (2, 1100), (3, 1300), (4, 1600)]:
        events[f"clear{n}"] = tone(f, 0.28, 0.45, 0.004, 0.28, f1=f*1.35, seed=SEED+n)
    events["combo"]      = tone(1500, 0.30, 0.5, 0.005, 0.30, f1=2200, vib=6, seed=SEED+10)
    events["gameover"]   = tone(300, 0.8, 0.6, 0.01, 0.8, f1=120, noise=0.2, seed=SEED+11)
    events["levelup"]    = tone(1000, 0.5, 0.55, 0.006, 0.5, f1=1500, seed=SEED+12)
    events["pause"]      = tone(500, 0.08, 0.4, 0.002, 0.08, shape="square", seed=SEED+13)
    events["unpause"]    = tone(620, 0.08, 0.4, 0.002, 0.08, shape="square", seed=SEED+14)
    events["start"]      = tone(700, 0.10, 0.5, 0.002, 0.10, f1=1400, seed=SEED+15)
    events["select"]     = tone(1000, 0.09, 0.45, 0.002, 0.09, f1=1600, seed=SEED+16)

    for name, smp in events.items():
        write_wav("sfx_" + name, smp)

    # header section: event table (sample-pool arrays, 16-bit signed, mono)
    names = sorted(events.keys())
    lines = [
        "// SFX (generated by tools/gen_sfx.py) — single static blob pool, mono 16-bit 44.1kHz",
        "static const unsigned int kSfxSampleRate = 44100;",
        "static const unsigned int kSfxBlobPool[1] = {0u};   // single blob (unused by DirectXTK in-memory ctor)",
    ]
    # direct memory pool: concatenate all events in order; offsets table
    blob = []
    for n in names:
        for s in events[n]:
            blob.append(int(max(-1.0, min(1.0, s)) * 32767))
    lines.append(f"static const unsigned int kSfxPoolLen = {len(blob)};")
    lines.append("static const short kSfxPool[] = {")
    for s in blob:
        lines.append(f"    {s},")
    lines.append("};")
    # per-event lut table: (start, len) samples
    lines.append("static const struct { const char* name; unsigned int id; unsigned int start, len; } kSfxLut[] = {")
    def fnv32(s):
        hsh = 2166136261
        for ch in s.encode():
            hsh = ((hsh ^ ch) * 16777619) & 0xffffffff
        return hsh
    off = 0
    for n in names:
        l = len(events[n])
        lines.append(f'    {{ "{n}", 0x{fnv32(n):08X}u, {off}, {l} }},')
        off += l
    lines.append("};")
    lines.append("static const int kSfxCount = %d;" % len(names))
    write_header("assets_sfx.h", lines, tag="sfx")
    print("wrote assets_sfx.h (section)")

if __name__ == "__main__":
    main()
