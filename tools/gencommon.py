#!/usr/bin/env python3
"""gencommon.py — shared header emitter for all generators (MINE, final; stable API).
Contract: single generated header with static arrays; deterministic; stable sha256 ids;
no PIL needed here; each generator calls write_header().
"""
import hashlib
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_DIR = os.path.join(ROOT, "assets", "src")
GEN_DIR = os.path.join(ROOT, "assets", "generated")

HEADER_NAME = "assets.h"          # single generated header (the game includes this)
MANIFEST_NAME = "manifest.json"   # tool manifest (sha256s, stable ids)
SECTION_ORDER = ["font", "cso", "atlas", "mesh", "sfx"]   # stable assembly order (contract)


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        h.update(f.read())
    return h.hexdigest()


def read_src(name):
    return open(os.path.join(SRC_DIR, name), "rb").read()


def write_src(name, data):
    p = os.path.join(SRC_DIR, name)
    with open(p, "wb") as f:
        f.write(data)
    return p


# ---- section storage ----
def write_section(tag, lines):
    os.makedirs(GEN_DIR, exist_ok=True)
    p = os.path.join(GEN_DIR, f"section_{tag}.inc")
    with open(p, "w", newline="\n", encoding="utf-8") as f:
        f.write(f"{tag}|\n")            # stable tag line (no trailing whitespace/newline)
        f.write("\n".join(lines))
    return p


def read_section(tag):
    p = os.path.join(GEN_DIR, f"section_{tag}.inc")
    if not os.path.exists(p):
        return None
    with open(p, encoding="utf-8") as f:
        data = f.read()
    assert data.splitlines()[0].strip() == f"{tag}|"  # stable tag line
    return data


def assemble_header():
    os.makedirs(GEN_DIR, exist_ok=True)
    hdr = ["// assets.h — GENERATED by tools (single header; static arrays). DO NOT EDIT.",
           "// generators write each section; assembly here is deterministic (stable order, no timestamps).",
           "", "#pragma once", "#include <cstddef>", "#include <cstdint>",
           "", "namespace tetris {", ""]
    manifest = {"assets": {}}
    parts = []
    for tag in SECTION_ORDER:
        content = read_section(tag)
        if content is None:
            continue
        lines = content.splitlines()
        assert lines and lines[0].strip() == f"{tag}|"   # stable tag line (storage marker)
        body = "\n".join(lines[1:])                      # strip marker line; body only
        parts.append((tag, body))
    for tag, content in parts:
        hdr.append("// ---- section: %s ----" % tag)
        hdr.append(content.strip())
        hdr.append("")
        manifest["assets"]["@" + tag] = {"sha256": hashlib.sha256(content.encode()).hexdigest()}
    # source inputs recorded for reproducibility
    if os.path.isdir(SRC_DIR):
        for fn in sorted(os.listdir(SRC_DIR)):
            if fn.endswith((".png", ".json", ".wav")):
                manifest["assets"][fn] = {"sha256": sha256_file(os.path.join(SRC_DIR, fn))}
    hdr += ["} // namespace tetris", ""]
    p = os.path.join(GEN_DIR, HEADER_NAME)
    with open(p, "w", newline="\n", encoding="utf-8") as f:
        f.write("\n".join(hdr))
    with open(os.path.join(GEN_DIR, MANIFEST_NAME), "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2, sort_keys=True)
    return p


# generators call this:
def write_header(name, lines, tag=None):
    write_section(tag or name.replace(".h", "").replace("assets_", ""), lines)
    return assemble_header()
