#!/usr/bin/env python3
"""gen_font.py — font raster + metrics generator (TTF -> PIL). — MINE, final.
Produces (contract: single generated header with static arrays, ASCII 32..126):
  assets/src/font_atlas.json  (glyph metrics, px-accurate, top-left origin)
  assets/generated/assets.h   — appended as FONT section (DirectXTK SpriteFont::Glyph layout)
Run standalone: py -3 tools/gen_font.py  (mechanical terminal run; this file final)
"""
import json
import os
import sys
from PIL import Image, ImageFont, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
from gencommon import write_header, sha256_file  # shared emitter (mine, stable)

# Contract: design size per HUD layout, plain ASCII 32..126 (96 glyphs), top-left origin.
DESIGN_PX = 72
FONT_CANDIDATES = [
    r"C:\Windows\Fonts\courierai02.ttf",   # contract-suggested (arbitron-like courier)
    r"C:\Windows\Fonts\cour.ttf",          # accepted fallback
    r"C:\Windows\Fonts\arialbd.ttf",
    r"C:\Windows\Fonts\consola.ttf",
]
ATLAS = r"C:\Windows\Fonts\cour.ttf"  # raster source (accepted; contract noted courierai02 preferred)

CHARS = list(range(32, 127))   # 96 glyphs
CELL_W, CELL_H = 48, 96         # design cell px at 2x supersample
COLS, ROWS = 12, 8              # 96 glyphs packed
S = 2                           # supersample factor

def main():
    font_path = None
    for c in FONT_CANDIDATES:
        if os.path.exists(c):
            font_path = c
            break
    # per contract prefer courierai02 if present
    if FONT_CANDIDATES[0] and os.path.exists(FONT_CANDIDATES[0]):
        font_path = FONT_CANDIDATES[0]
    print("font:", font_path)
    font = ImageFont.truetype(font_path, DESIGN_PX * S)

    sheet = Image.new("RGBA", (COLS * CELL_W * S, ROWS * CELL_H * S), (0, 0, 0, 0))
    d = ImageDraw.Draw(sheet)
    meta = {"source": font_path, "design_px": DESIGN_PX, "supersample": S,
            "cell": [CELL_W, CELL_H], "cols": COLS, "rows": ROWS,
            "baseline": None, "glyphs": []}

    # get overall metrics from a representative string (ascii only)
    asc, desc = font.getmetrics()
    meta["baseline"] = round(asc / S, 1)   # ascender in design px
    meta["line_spacing"] = round((asc + desc) / S, 1)

    for idx, ch in enumerate(CHARS):
        col, row = idx % COLS, idx // COLS
        x0, y0 = col * CELL_W * S, row * CELL_H * S
        # draw glyph white on transparent, anchored to the CELL TOP (y offset 0) so DrawText y = visual top
        d.text((x0 + S, y0), chr(ch), font=font, fill=(255, 255, 255, 255), anchor=None, stroke_width=0)
        # ink bbox in cell-space design px (the glyph is drawn at +S horizontally and +asc vertically)
        bbox = font.getbbox(chr(ch))         # (l,t,r,b) relative to the drawing anchor
        adv = font.getlength(chr(ch)) if chr(ch) != " " else font.getlength("M")  # fixed width for space
        if bbox[2] <= bbox[0] or bbox[3] <= bbox[1]:
            rect = [0, 0, 1, 1]; offx, offy = 0.0, 0.0   # blank glyph: 1px empty quad
        else:
            rect = [round((x0 + S + bbox[0]) / S), round((y0 + bbox[1]) / S),
                    round((x0 + S + bbox[2]) / S), round((y0 + bbox[3]) / S)]
            offx, offy = round((S + bbox[0]) / S, 3), round(bbox[1] / S, 3)
        meta["glyphs"].append({
            "char": chr(ch), "code": ch,
            "rect": rect,
            "offset": [offx, offy],
            # DirectXTK advance = Subrect width + XAdvance, so XAdvance is the extra space after the glyph
            "advance": round(adv / S - (rect[2] - rect[0]), 5),
        })

    # save png (downscale supersample) + json
    sheet.resize((COLS * CELL_W, ROWS * CELL_H), Image.NEAREST).save(
        os.path.join(ROOT, "assets", "src", "font_sheet.png"))
    with open(os.path.join(ROOT, "assets", "src", "font_atlas.json"), "w", encoding="utf-8") as f:
        json.dump(meta, f, indent=2)

    # header section: DirectXTK SpriteFont::Glyph layout (Character uint32; RECT; floats)
    lines = [
        "// FONT (generated by tools/gen_font.py) — DirectXTK SpriteFont::Glyph layout, px-accurate",
        "// fields per DirectXTK: Character uint32; RECT Subrect (L,T,R,B, atlas px); float XOffset,YOffset,XAdvance",
        "// offsets relative to top-left origin; draw baseline via ascender",
        f"static const int kFontFirst = {CHARS[0]};",
        f"static const int kFontCount = {len(CHARS)};",
        f"static const float kFontLineSpacing = {meta['line_spacing']}f;",
        "static const struct { unsigned int Character; int L, T, R, B; float XOffset, YOffset, XAdvance; } kFontGlyphs[96] = {",
    ]
    for g in meta["glyphs"]:
        r, io = g["rect"], g["offset"]
        lines.append(f"    {{ {g['code']}, {r[0]}, {r[1]}, {r[2]}, {r[3]}, {io[0]:.3f}f, {io[1]:.3f}f, {g['advance']:.5f}f }},")
    lines.append("};")
    write_header(os.path.join(ROOT, "assets", "generated", "assets_font.h"), lines, tag="font")
    print("wrote assets_font.h (section)")

if __name__ == "__main__":
    main()
